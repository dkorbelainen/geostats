"""Render benchmarks/forecast.md from the results of benchmarks/forecast/train.py."""

from __future__ import annotations

import json
import subprocess
from typing import Any

from benchmarks.forecast.train import FIRST_ORIGIN, FOLDS, RESULTS_PATH, ROOT

REPORT_PATH = ROOT / "benchmarks" / "forecast.md"
_MODES = {"moving": "Moving", "nomove": "No move", "nmpz": "NMPZ"}
_CRITERIA = {
    "beats_no_change_7d": "7 days: MAE below no change, interval excludes zero",
    "beats_no_change_30d": "30 days: MAE below no change, interval excludes zero",
    "no_tier_worse": "No rating tier is worse than no change at either horizon",
}


def _interval(values: list[float]) -> str:
    diff, low, high = values
    return f"{diff:+.1f} [{low:+.1f}, {high:+.1f}]"


def _metrics(name: str, row: dict[str, float]) -> str:
    direction = "—" if row["direction"] != row["direction"] else f"{row['direction']:.0%}"
    return (
        f"| {name} | {row['mae']:.1f} | {row['rmse']:.1f} | {row['median_ae']:.1f} | {direction} |"
    )


def _tier(tier: dict[str, Any]) -> str:
    if tier["from"] is None:
        return f"below {tier['to']:.0f}"
    if tier["to"] is None:
        return f"{tier['from']:.0f} and above"
    return f"{tier['from']:.0f}–{tier['to']:.0f}"


def _horizon(days: str, result: dict[str, Any]) -> list[str]:
    test = result["test"]
    families = result["families"]
    lines = [
        f"### {days} days",
        "",
        f"{test['forecasts']} forecasts for {test['accounts']} accounts. "
        f"Selected: `{result['selected']}`.",
        "",
        "| Forecast | MAE | RMSE | Median error | Direction |",
        "|---|---|---|---|---|",
        _metrics("No change", test["no_change"]),
        _metrics("Theil–Sen trend", test["theil_sen"]),
        _metrics(f"Best ridge (`{families['ridge']['name']}`)", families["ridge"]),
        _metrics(f"Best boosting (`{families['gbr']['name']}`)", families["gbr"]),
        _metrics("**Selected model**", test["model"]),
        "",
        "| MAE difference | 95% interval |",
        "|---|---|",
        f"| Selected model − no change | {_interval(test['model_vs_no_change'])} |",
        f"| Selected model − Theil–Sen trend | {_interval(test['model_vs_theil_sen'])} |",
        f"| Theil–Sen trend − no change | {_interval(test['theil_sen_vs_no_change'])} |",
        "",
    ]
    return lines


def render(results: dict[str, Any], commit: str) -> str:
    horizons = results["horizons"]
    lines = [
        "# Rating forecast benchmark",
        "",
        f"Generated by `benchmarks/forecast/report.py` at `{commit}`. Do not edit.",
        "",
        "## Setup",
        "",
        f"- Data: {results['snapshots']} snapshots of {results['accounts']} accounts, "
        f"{results['since']} to {results['until']} (exclusive).",
        f"- A forecast is made every 7 days from {FIRST_ORIGIN.date().isoformat()}, "
        "7 and 30 days ahead, for accounts with enough history and a rating known at the "
        "target date.",
        f"- Models are selected on forecasts resolved by {results['test_start']} "
        f"({FOLDS}-fold cross-validation grouped by account) and tested on forecasts made "
        "from that date.",
        "- Intervals: cluster bootstrap over accounts, 2000 resamples.",
        "- Direction: share of correct signs where the predicted and the actual change are "
        "both non-zero.",
        "",
        "## Result",
        "",
    ]
    for days, result in horizons.items():
        lines += _horizon(days, result)
    lines += [
        "## Criteria",
        "",
        "1–3 were fixed after one exploratory look at the test period with three "
        "configurations; 4 is blind.",
        "",
    ]
    for number, (key, text) in enumerate(_CRITERIA.items(), start=1):
        lines.append(f"{number}. {text}: **{'pass' if results['criteria'][key] else 'fail'}**")
    lines += [
        f"{len(_CRITERIA) + 1}. 7 days on forecasts made after {results['until']}: "
        "**pending**, needs a later export",
        "",
        "## Rating tiers",
        "",
        "Selected model − no change, MAE.",
        "",
        "| Rating | " + " | ".join(f"{days} days" for days in horizons) + " |",
        "|---|" + "---|" * len(horizons),
    ]
    tiers = [result["tiers"] for result in horizons.values()]
    for row in zip(*tiers, strict=True):
        cells = " | ".join(_interval(tier["model_vs_no_change"]) for tier in row)
        lines.append(f"| {_tier(row[0])} | {cells} |")
    lines += [
        "",
        "## Mode ratings",
        "",
        "The model selected on the overall rating, applied to each mode rating. "
        "MAE: no change / Theil–Sen trend / model, then model − no change. "
        "The site serves a forecast for the overall and the no-move rating.",
        "",
        "| Mode | " + " | ".join(f"{days} days" for days in horizons) + " |",
        "|---|" + "---|" * len(horizons),
    ]
    for mode, label in _MODES.items():
        parts = [result["modes"][mode] for result in horizons.values()]
        cells = " | ".join(
            f"{part['no_change']['mae']:.1f} / {part['theil_sen']['mae']:.1f} / "
            f"{part['model']['mae']:.1f}, {_interval(part['model_vs_no_change'])}"
            for part in parts
        )
        lines.append(f"| {label} | {cells} |")
    lines += ["", "## Model selection", "", "Cross-validated MAE on development forecasts.", ""]
    lines += ["| Candidate | " + " | ".join(f"{days} days" for days in horizons) + " |"]
    lines += ["|---|" + "---|" * len(horizons)]
    for name in next(iter(horizons.values()))["cross_validation"]:
        cells = " | ".join(f"{r['cross_validation'][name]:.2f}" for r in horizons.values())
        lines.append(f"| `{name}` | {cells} |")
    lines += [
        "",
        "## Reproduce",
        "",
        "```",
        "benchmarks/export.sh <ssh-host>",
        "python -m benchmarks.forecast.train benchmarks/data/snapshots.csv.gz",
        "python -m benchmarks.forecast.report",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    head = ["git", "rev-parse", "--short", "HEAD"]
    commit = subprocess.run(head, cwd=ROOT, capture_output=True, text=True, check=True).stdout
    REPORT_PATH.write_text(render(json.loads(RESULTS_PATH.read_text()), commit.strip()))


if __name__ == "__main__":
    main()
